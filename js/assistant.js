/**
 * Чат-ассистент — детерминированные правила, без обращения к какой-либо
 * модели и без сети. Честно говорит об этом в каждом ответе.
 *
 * Важно про предложения об обновлении плана: каждое имеет уникальный id
 * (makeId), и карточка в чате привязывается к КОНКРЕТНОМУ объекту
 * предложения через замыкание, а не читает общее «текущее» состояние заново.
 * Раньше при получении нового ответа старое предложение молча становилось
 * недействительным (state.pendingProposal обнулялся или перезаписывался),
 * но кнопка «Применить» на старой карточке при клике всё равно обращалась
 * к этому общему состоянию — и падала с TypeError, если оно уже стало null.
 * Теперь карточка не может обратиться к чужим/несуществующим данным: она
 * либо работает с тем предложением, с которым была создана, либо явно
 * помечена устаревшей и кнопки в ней отключены.
 */

import { makeId, dateFromToday } from './plan.js';

/** Детерминированная эвристика ответа. */
export function heuristicReply(userMessage, { profileName, steps }) {
  const name = profileName || 'коллега';
  const lower = userMessage.toLowerCase();

  if (/дедлайн|срок|перенес|продлил|продлен|не успе/.test(lower) && steps.length) {
    const target = steps.find((s) => s.status !== 'done') ?? steps[0];
    return {
      text:
        `${name}, если срок по шагу «${target.title}» изменился, план стоит пересобрать вокруг новой даты — ` +
        'от неё зависят визовый блок и бронь жилья. Я подготовил предложение по обновлению, посмотрите его ниже.' +
        '\n\n(Офлайн-ассистент: ответ собран по заранее заданным правилам, а не языковой моделью.)',
      proposal: {
        id: makeId('proposal'),
        rationale: 'Вы сообщили об изменении срока — сдвигаю дедлайн ближайшего незавершённого шага.',
        operations: [
          {
            op: 'update_step',
            stepId: target.id,
            deadline: dateFromToday(30),
            description: `${target.description} Срок обновлён по вашему сообщению.`,
          },
        ],
      },
    };
  }

  if (/зачем|почему|why/.test(lower) && steps.length) {
    const target = steps.find((s) => s.status !== 'done') ?? steps[0];
    return {
      text:
        `${name}, шаг ${target.order} — «${target.title}». ${target.why}` +
        '\n\n(Офлайн-ассистент: ответ собран из данных плана без обращения к какой-либо модели.)',
      proposal: null,
    };
  }

  if (/виз/.test(lower)) {
    const visaStep = steps.find((s) => s.phase === 'visa');
    return {
      text: visaStep
        ? `${name}, по визе — шаг ${visaStep.order} «${visaStep.title}»: ${visaStep.description}`
        : `${name}, в этом плане нет отдельного визового шага — уточните требования у консульства.`,
      proposal: null,
    };
  }

  return {
    text:
      `${name}, это офлайн-ассистент: он отвечает по заранее заданным правилам, а не языковой моделью. ` +
      `В вашем плане ${steps.length} шагов, ближайший — «${steps[0]?.title ?? 'не задан'}». ` +
      'Попробуйте спросить про срок, конкретный шаг или визу.',
    proposal: null,
  };
}
